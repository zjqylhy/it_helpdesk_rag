from collections.abc import AsyncIterator
from typing import Protocol

from helpdesk.domain.models import Row
from helpdesk.domain.rag import Reply, TextDelta, Usage


class Models(Protocol):
    async def structured(self, stage: str, system: str, payload: Row, limit: int) -> Reply: ...
    async def embed(self, texts: list[str]) -> tuple[list[list[float]], Usage]: ...
    async def rank(self, query: str, texts: list[str]) -> tuple[list[int], Usage]: ...
    def generate(self, system: str, payload: Row, limit: int) -> AsyncIterator[TextDelta]: ...


class AttemptLedger(Protocol):
    async def start_attempt(self, run_id: str, stage: str, reserved: int) -> str: ...
    async def end_attempt(self, attempt_id: str, status: str, usage: Usage) -> None: ...


class RunJournal(AttemptLedger, Protocol):
    async def start_run(self, message_id: str | None, manifest: Row) -> str: ...
    async def finish_run(self, run_id: str, status: str, trace: Row) -> None: ...
