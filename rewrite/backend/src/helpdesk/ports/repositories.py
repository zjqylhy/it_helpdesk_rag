from collections.abc import AsyncIterator
from contextlib import AbstractAsyncContextManager
from dataclasses import dataclass
from typing import Protocol

from helpdesk.domain.models import Principal, Row


class IdentityRepository(Protocol):
    async def user_by_name(self, username: str) -> Row | None: ...
    async def user(self, user_id: str, *, lock: bool = False) -> Row | None: ...
    async def principal(self, token_hash: str) -> Principal | None: ...
    async def create_user(self, values: Row) -> Row: ...
    async def save_token(self, digest: str, user_id: str, hours: int) -> None: ...
    async def delete_token(self, digest: str) -> None: ...
    async def users(self) -> list[Row]: ...


class AccessRepository(Protocol):
    async def revision(self, *, lock: bool = False) -> int: ...
    async def audit(self, actor: str, action: str, target: str, details: Row) -> int: ...
    async def groups(self) -> list[Row]: ...
    async def create_group(self, name: str) -> Row: ...
    async def set_members(self, group_id: str, user_ids: list[str]) -> None: ...
    async def set_document_access(self, document_id: str, visibility: str, groups: list[str]) -> None: ...
    async def disable_user(self, user_id: str, disabled: bool) -> None: ...
    async def update_user(self, user_id: str, usage_kind: str | None, password_hash: str | None) -> None: ...
    async def events(self) -> list[Row]: ...
    async def document_access(self, document_id: str) -> Row: ...


class CatalogRepository(Protocol):
    async def knowledge_bases(self, principal: Principal) -> list[Row]: ...
    async def create_kb(self, name: str, organization: str) -> Row: ...
    async def default_search(self, kb_id: str, enabled: bool) -> Row: ...
    async def documents(self, principal: Principal, kb_id: str | None) -> list[Row]: ...
    async def document(self, principal: Principal, document_id: str, *, lock: bool = False) -> Row: ...
    async def versions(self, document_id: str) -> list[Row]: ...
    async def version(self, principal: Principal, version_id: str) -> Row: ...
    async def duplicate(self, kb_id: str, content_hash: str) -> bool: ...
    async def storage_key_in_use(self, key: str) -> bool: ...
    async def queue_document(self, kb_id: str, document_id: str | None, values: Row) -> Row: ...
    async def set_enabled(self, document_id: str, enabled: bool) -> Row: ...
    async def retry(self, job_id: str) -> Row: ...
    async def chunks(self, document_id: str, version_id: str) -> list[Row]: ...


class ConversationRepository(Protocol):
    async def create_session(self, principal: Principal, kb_ids: list[str]) -> Row: ...
    async def sessions(self, principal: Principal) -> list[Row]: ...
    async def session(self, principal: Principal, session_id: str) -> Row: ...
    async def messages(self, session_id: str) -> list[Row]: ...
    async def provenance_visible(self, principal: Principal, provenance: Row) -> bool: ...
    async def admit(
        self, session_id: str, request_id: str, question: str, principal: Principal
    ) -> tuple[Row, bool]: ...
    async def finish(
        self, message_id: str, status: str, answer: str, citations: list[Row], provenance: Row
    ) -> Row: ...


@dataclass(frozen=True)
class Repositories:
    identity: IdentityRepository
    access: AccessRepository
    catalog: CatalogRepository
    conversations: ConversationRepository


class UnitOfWork(Protocol):
    def __call__(self) -> AbstractAsyncContextManager[Repositories]: ...


class FileStore(Protocol):
    async def save(self, parts: AsyncIterator[bytes], suffix: str) -> tuple[str, str, int]: ...
    async def remove(self, key: str) -> None: ...
    async def read(self, key: str, expected_hash: str) -> bytes: ...
